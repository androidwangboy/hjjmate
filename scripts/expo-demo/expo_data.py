def _skill_md(name, zh, desc, version, author, tags, params, tools, body):
    import json as _json
    lines = ["---", f"name: {name}", f"nameZh: {zh}", f"description: {desc}",
             f"version: {version}", "type: custom", f"author: {author}"]
    if tools:
        lines.append("tools:")
        for t in tools:
            lines.append(f"  - {t}")
    lines.append("tags:")
    for t in tags:
        lines.append(f"  - {t}")
    if params:
        lines.append("parameters:")
        for p in params:
            lines.append(f"  - name: {p['name']}")
            lines.append(f"    type: {p.get('type', 'string')}")
            lines.append(f"    required: {str(p.get('required', False)).lower()}")
            lines.append(f"    description: {p['description']}")
    lines.append("---")
    lines.append("")
    lines.append(body.strip())
    return "\n".join(lines)


